"""Human-readable renderings of entries: provenance cards and the catalogue table."""

from __future__ import annotations

from almanac.api import Almanac
from almanac.models import Entry, RuleSpec


def validity(entry: Entry) -> str:
    if entry.kind == "rule":
        end = entry.valid_to.isoformat() if entry.valid_to else "open"
        return f"{entry.valid_from} to {end}"
    assert entry.observed_period is not None
    return f"observed {entry.observed_period.start} to {entry.observed_period.end}"


def publishers(entry: Entry) -> list[str]:
    seen: list[str] = []
    for item in entry.evidence:
        if item.publisher not in seen:
            seen.append(item.publisher)
    return seen


def render_card(entry: Entry) -> str:
    lines = [
        f"{entry.id}",
        f"  {entry.title}",
        f"  kind {entry.kind} · domain {entry.domain} · region {entry.region} · tier {entry.tier} · status {entry.status}",
        f"  valid {validity(entry)}",
    ]
    if isinstance(entry.spec, RuleSpec):
        from_source = sum(1 for v in entry.spec.vectors if v.origin == "source")
        lines.append(f"  rule {entry.spec.implementation} · {len(entry.spec.vectors)} vectors ({from_source} from the source)")
    lines.append("  evidence")
    for index, item in enumerate(entry.evidence, start=1):
        lines.append(f"    {index}. {item.publisher}: {item.title}")
        lines.append(f"       {item.locator} = {item.value!r} [{item.unit}]")
        lines.append(f"       {item.url}")
        lines.append(f"       sha256 {item.content_sha256[:16]}… · accessed {item.accessed_at} · licence {item.source_license}")
    if entry.assumed:
        lines.append("  assumed")
        for assumption in entry.assumed:
            lines.append(f"    - {assumption.parameter} ({assumption.method}): {assumption.rationale}")
    if entry.tags or entry.use_cases:
        lines.append(f"  tags {', '.join(entry.tags)} · use cases {', '.join(entry.use_cases)}")
    lines.append(f"  tests {len(entry.tests)}")
    lines.append("  notes")
    lines.extend(f"    {line}" for line in entry.notes.strip().splitlines())
    return "\n".join(lines)


def render_catalogue(almanac: Almanac) -> str:
    rows = sorted(almanac, key=lambda e: (e.domain, e.region, e.id))
    counts = {"verified": 0, "license-review": 0, "draft": 0}
    for entry in rows:
        counts[entry.status] += 1
    lines = [
        "# Catalogue",
        "",
        "Generated by `uv run almanac catalogue --write CATALOGUE.md`. Do not edit by hand.",
        "",
        f"{len(rows)} entries: {counts['verified']} verified, {counts['license-review']} awaiting licence review, {counts['draft']} draft.",
        "",
        "## By business problem",
        "",
        "| Use case | Entries |",
        "| --- | --- |",
    ]
    by_use_case: dict[str, list[Entry]] = {}
    for entry in rows:
        for use_case in entry.use_cases:
            by_use_case.setdefault(use_case, []).append(entry)
    for use_case, members in sorted(by_use_case.items()):
        links = ", ".join(f"[{e.id}]({_rel(almanac, e)})" for e in members)
        lines.append(f"| {use_case} | {links} |")
    lines += [
        "",
        "## All entries",
        "",
        "| Entry | Domain | Region | Kind | Tier | Status | Validity | Sources | Tags |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in rows:
        lines.append(
            f"| [{entry.id}]({_rel(almanac, entry)})<br>{entry.title} | {entry.domain} | {entry.region} | {entry.kind} | {entry.tier} "
            f"| {entry.status} | {validity(entry)} | {'; '.join(publishers(entry))} | {', '.join(entry.tags)} |"
        )
    return "\n".join(lines) + "\n"


def _rel(almanac: Almanac, entry: Entry) -> str:
    path = almanac.path(entry.id)
    return path.relative_to(path.parents[3]).as_posix()
